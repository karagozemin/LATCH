import { readFileSync, writeFileSync } from "node:fs";
import { TESTNET_NETWORK } from "../config/testnet.mjs";

const deployment = JSON.parse(readFileSync("deployments/testnet.json", "utf8"));
if (deployment.networkPassphrase !== TESTNET_NETWORK.passphrase) {
  throw new Error("Deployment network does not match config/testnet.mjs");
}

const generated = `// Generated by scripts/sync-testnet-config.mjs. Do not edit by hand.
export const TESTNET = ${JSON.stringify(
  {
    ...TESTNET_NETWORK,
    proofContract: deployment.latch.contractId,
    wasmHash: deployment.latch.wasmSha256,
    proof: {
      deposit: deployment.proof.transactionHashes.deposit,
      hold: deployment.proof.transactionHashes.createHoldPrimary,
      holdSecondary: deployment.proof.transactionHashes.createHoldSecondary,
      pay: deployment.proof.transactionHashes.pay,
      capture: deployment.proof.transactionHashes.capture,
      release: deployment.proof.transactionHashes.release,
    },
    decline: deployment.proof.decline,
  },
  null,
  2,
)} as const;
`;

writeFileSync("sites/latch-demo/src/testnet-config.ts", generated);
